"""HTML report: one offline file, summary first, drill-down second (FR-31, NFR-29).

No scripts and no external links: the page opens from disk. Every piece of text that
came from a test is escaped. Status is written as a word (not colour alone), every
screenshot has a text alternative, tables have captions and column headers, and the
palette meets the WCAG AA contrast ratio (checked in the tests).
"""

from __future__ import annotations

import re
from collections.abc import Collection
from html import escape

from aitaf.reporting.model import ReportData, ReportTest, clean_log, format_value

PALETTE = {
    "text": "#1a1a1a",
    "background": "#ffffff",
    "muted": "#4a4a4a",
    "link": "#0b3d91",
    "badge_text": "#ffffff",
    "pass": "#0b5d1e",
    "fail": "#9b1c1c",
    "error": "#7a3e00",
    "skip": "#4a4a4a",
    "rule": "#c8c8c8",
}
_BADGE = {"passed": "pass", "failed": "fail", "error": "error", "skipped": "skip"}
LOG_EXCERPT = 800
_SAFE_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")


def safe_name(name: str) -> bool:
    """A file name that cannot leave the evidence directory or break an attribute."""
    return bool(name) and bool(_SAFE_NAME.match(name)) and ".." not in name


def linkable(name: str, available: Collection[str] | None) -> bool:
    return safe_name(name) and (available is None or name in available)


def _css() -> str:
    p = PALETTE
    return (
        f"body{{font-family:Arial,Helvetica,sans-serif;max-width:60rem;margin:1.5rem auto;"
        f"padding:0 1rem;color:{p['text']};background:{p['background']};line-height:1.45}}"
        f"a{{color:{p['link']}}}h1,h2,h3{{margin-top:1.6rem}}"
        f"table{{border-collapse:collapse;width:100%;margin:.6rem 0}}"
        f"caption{{text-align:left;font-weight:bold;padding:.3rem 0}}"
        f"th,td{{border:1px solid {p['rule']};padding:.35rem .5rem;text-align:left;vertical-align:top}}"
        f".muted{{color:{p['muted']}}}"
        f".badge{{color:{p['badge_text']};padding:.05rem .45rem;border-radius:.2rem;font-size:.85rem;"
        f"font-weight:bold}}"
        + "".join(f".b-{key}{{background:{p[key]}}}" for key in ("pass", "fail", "error", "skip"))
        + "details{border:1px solid "
        + p["rule"]
        + ";margin:.5rem 0;padding:.4rem .7rem}summary{cursor:pointer;font-weight:bold}"
        "img{max-width:100%;border:1px solid " + p["rule"] + "}"
    )


def _badge(status: str) -> str:
    return f'<span class="badge b-{_BADGE.get(status, "skip")}">{escape(status.upper())}</span>'


def _results_table(data: ReportData) -> str:
    rows = []
    for t in data.tests:
        category = t.analysis.category if t.analysis else ""
        rows.append(
            "<tr>"
            f"<td>{escape(t.tc_id)}</td><td>{escape(t.title)}</td>"
            f"<td>{escape(t.requirement_id) or '-'}</td><td>{_badge(t.status)}</td>"
            f"<td>{t.duration_ms} ms</td><td>{t.attempts}</td>"
            f"<td>{'yes' if t.healed else 'no'}</td><td>{escape(category) or '-'}</td></tr>"
        )
    head = "".join(
        f'<th scope="col">{name}</th>'
        for name in (
            "Test case",
            "Title",
            "Requirement",
            "Status",
            "Duration",
            "Attempts",
            "Healed",
            "Failure category",
        )
    )
    return (
        "<table>\n<caption>Results of every executed test</caption>\n"
        f"<thead><tr>{head}</tr></thead>\n<tbody>\n" + "\n".join(rows) + "\n</tbody>\n</table>"
    )


def _failure(t: ReportTest, available: Collection[str] | None) -> str:
    a = t.analysis
    label = ""
    if a is not None and a.source == "llm":
        label = (
            f" [AI-generated by {escape(a.model or '')}, prompt {escape(a.prompt_version or '')}]"
        )
    elif a is not None and a.source == "fallback":
        label = " [no explanation available]"
    head = f"{escape(t.tc_id)}: {escape(a.category) if a else 'not analysed'}"
    if a is not None:
        head += f" (confidence {a.confidence:.2f}, {escape(a.source)})"
    parts = [f"<details>\n<summary>{head}{label}</summary>"]
    if a is not None:
        parts.append(f"<p><strong>Cause:</strong> {escape(a.root_cause)}</p>")
        parts.append(f"<p><strong>Next step:</strong> {escape(a.remediation)}</p>")
        parts.append(
            f'<p class="muted">Cluster {escape(a.cluster_id)}; evidence: {escape(", ".join(a.evidence_refs))}</p>'
        )
    if linkable(t.screenshot, available):
        parts.append(
            f'<p><img src="evidence/{escape(t.screenshot)}" '
            f'alt="Screenshot of test {escape(t.tc_id)} at failure"></p>'
        )
    if t.log.strip():
        parts.append(f"<pre>{escape(clean_log(t.log.strip())[-LOG_EXCERPT:])}</pre>")
    links = []
    if linkable(t.dom_snapshot, available):
        links.append(f'<a href="evidence/{escape(t.dom_snapshot)}">page snapshot</a>')
    links.append(f'<a href="logs/{escape(t.result_id)}.txt">log</a>')
    parts.append("<p>" + " | ".join(links) + "</p>")
    parts.append("</details>")
    return "\n".join(parts)


def _main_problem_html(data: ReportData) -> str:
    problem = data.main_problem
    return f"<p><strong>{escape(problem)}</strong></p>\n" if problem else ""


def render_html(data: ReportData, available: Collection[str] | None = None) -> str:
    """The complete report as one HTML document."""
    failed = [t for t in data.tests if t.status in ("failed", "error")]
    metrics = "\n".join(
        f"<tr><td>{escape(m.label)}</td><td>{escape(format_value(m))}</td><td>{escape(m.basis)}</td></tr>"
        for m in data.metrics
    )
    failures = (
        "\n".join(_failure(t, available) for t in failed) if failed else "<p>No failed tests.</p>"
    )
    events = "\n".join(
        f"<tr><td>{escape(e.step_ref)}</td><td>{escape(e.strategy_used)}</td>"
        f"<td>{escape(e.outcome)}</td><td>{e.confidence:.2f}</td>"
        f"<td>{'yes' if e.approved else 'no'}</td></tr>"
        for e in data.healing_events
    )
    healing = (
        "<table>\n<caption>Self-healing events (proposed events need human approval)</caption>\n"
        '<thead><tr><th scope="col">Step</th><th scope="col">Method</th><th scope="col">Outcome</th>'
        '<th scope="col">Confidence</th><th scope="col">Approved</th></tr></thead>\n'
        f"<tbody>\n{events}\n</tbody>\n</table>"
        if data.healing_events
        else "<p>No self-healing events in this run.</p>"
    )
    trace = "\n".join(
        f"<tr><td>{escape(r.requirement_id) or '-'}</td><td>{escape(r.tc_id)}</td>"
        f"<td>{escape(r.script_path) or '-'}</td><td>{escape(r.status.upper())}</td>"
        f"<td>{escape(r.analysis_category) or '-'}</td></tr>"
        for r in data.trace
    )
    notes = [
        f"Figures come from the stored data of run {escape(data.run.run_id)}"
        + (f" and source run {escape(data.source_run_id)}." if data.source_run_id else "."),
        "A metric shown as n/a could not be computed from the stored data.",
    ]
    if data.provider in ("mock", "mixed"):
        notes.append(
            "Some or all AI output comes from the deterministic mock provider, not a live model."
        )
    if data.has_ai_text:
        notes.append("Explanations marked AI-generated come from a model: review them before use.")
    note_items = "".join(f"<li>{n}</li>" for n in notes)
    return (
        "<!DOCTYPE html>\n"
        '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        f"<title>{escape(data.title)}</title>\n<style>{_css()}</style>\n</head>\n<body>\n"
        f"<h1>{escape(data.title)}</h1>\n"
        f'<h2 id="summary">Summary</h2>\n<p>{escape(data.summary_line)}</p>\n'
        f"{_main_problem_html(data)}"
        f"<p>Run {escape(data.run.run_id)} on {escape(data.run.environment)}; "
        f"generated {data.generated_at:%Y-%m-%d %H:%M} UTC.</p>\n"
        f"<p>Provider: {escape(data.provider)}</p>\n"
        f'<h2 id="metrics">Metrics</h2>\n<table>\n<caption>Metrics computed from stored data</caption>\n'
        '<thead><tr><th scope="col">Metric</th><th scope="col">Value</th><th scope="col">Basis</th></tr></thead>\n'
        f"<tbody>\n{metrics}\n</tbody>\n</table>\n"
        f'<h2 id="results">Results</h2>\n{_results_table(data)}\n'
        f'<h2 id="failures">Failure analysis</h2>\n{failures}\n'
        f'<h2 id="healing">Self-healing</h2>\n{healing}\n'
        '<h2 id="trace">Traceability</h2>\n<table>\n<caption>Requirement to test case to script to result</caption>\n'
        '<thead><tr><th scope="col">Requirement</th><th scope="col">Test case</th><th scope="col">Script</th>'
        '<th scope="col">Status</th><th scope="col">Failure category</th></tr></thead>\n'
        f"<tbody>\n{trace}\n</tbody>\n</table>\n"
        f'<h2 id="notes">Notes and limits</h2>\n<ul>{note_items}</ul>\n'
        "</body>\n</html>\n"
    )
