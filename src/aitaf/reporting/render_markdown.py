"""Markdown report from the same data model as the HTML (FR-32).

The figures come from the same formatting function, so the two files show identical
numbers. Table cells are cleaned of pipes and line breaks.
"""

from __future__ import annotations

from collections.abc import Collection

from aitaf.reporting.model import ReportData, clean_log, format_value
from aitaf.reporting.render_html import LOG_EXCERPT, linkable


def _cell(text: str) -> str:
    return " ".join(text.replace("|", "\\|").split())


def render_markdown(data: ReportData, available: Collection[str] | None = None) -> str:
    """The complete report as Markdown."""
    lines = [
        f"# {_cell(data.title)}",
        "",
        "## Summary",
        "",
        data.summary_line,
        "",
        *([f"**{_cell(data.main_problem)}**", ""] if data.main_problem else []),
        f"Run {data.run.run_id} on {_cell(data.run.environment)}; "
        f"generated {data.generated_at:%Y-%m-%d %H:%M} UTC.",
        "",
        f"Provider: {data.provider}",
        "",
        "## Metrics",
        "",
        "| Metric | Value | Basis |",
        "|---|---|---|",
    ]
    lines += [
        f"| {_cell(m.label)} | {_cell(format_value(m))} | {_cell(m.basis)} |" for m in data.metrics
    ]
    lines += [
        "",
        "## Results",
        "",
        "| Test case | Title | Requirement | Status | Duration | Attempts | Healed | "
        "Failure category |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for t in data.tests:
        category = t.analysis.category if t.analysis else "-"
        lines.append(
            f"| {_cell(t.tc_id)} | {_cell(t.title)} | {_cell(t.requirement_id) or '-'} | "
            f"{t.status.upper()} | {t.duration_ms} ms | {t.attempts} | "
            f"{'yes' if t.healed else 'no'} | {category} |"
        )
    lines += ["", "## Failure analysis", ""]
    failed = [t for t in data.tests if t.status in ("failed", "error")]
    if not failed:
        lines.append("No failed tests.")
    for t in failed:
        a = t.analysis
        lines.append(f"### {_cell(t.tc_id)}: {a.category if a else 'not analysed'}")
        lines.append("")
        if a is not None:
            label = ""
            if a.source == "llm":
                label = f" [AI-generated by {a.model}, prompt {a.prompt_version}]"
            lines.append(
                f"Confidence {a.confidence:.2f} ({a.source}){label}; cluster {a.cluster_id}."
            )
            lines.append("")
            lines.append(f"- Cause: {_cell(a.root_cause)}")
            lines.append(f"- Next step: {_cell(a.remediation)}")
            lines.append(f"- Evidence: {_cell(', '.join(a.evidence_refs))}")
        if linkable(t.screenshot, available):
            lines += ["", f"![Screenshot of test {t.tc_id} at failure](evidence/{t.screenshot})"]
        if t.log.strip():
            excerpt = clean_log(t.log.strip())[-LOG_EXCERPT:].replace("```", "'''")
            lines += ["", "```text", excerpt, "```"]
        links = []
        if linkable(t.dom_snapshot, available):
            links.append(f"[page snapshot](evidence/{t.dom_snapshot})")
        links.append(f"[log](logs/{t.result_id}.txt)")
        lines += ["", " | ".join(links), ""]
    lines += ["## Self-healing", ""]
    if data.healing_events:
        lines += ["| Step | Method | Outcome | Confidence | Approved |", "|---|---|---|---|---|"]
        lines += [
            f"| {_cell(e.step_ref)} | {e.strategy_used} | {e.outcome} | {e.confidence:.2f} | "
            f"{'yes' if e.approved else 'no'} |"
            for e in data.healing_events
        ]
    else:
        lines.append("No self-healing events in this run.")
    lines += [
        "",
        "## Traceability",
        "",
        "| Requirement | Test case | Script | Status | Failure category |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {_cell(r.requirement_id) or '-'} | {_cell(r.tc_id)} | {_cell(r.script_path) or '-'} | "
        f"{r.status.upper()} | {r.analysis_category or '-'} |"
        for r in data.trace
    ]
    lines += ["", "## Notes and limits", ""]
    lines.append(
        f"- Figures come from the stored data of run {data.run.run_id}"
        + (f" and source run {data.source_run_id}." if data.source_run_id else ".")
    )
    lines.append("- A metric shown as n/a could not be computed from the stored data.")
    if data.provider in ("mock", "mixed"):
        lines.append(
            "- Some or all AI output comes from the deterministic mock provider, not a live model."
        )
    if data.has_ai_text:
        lines.append(
            "- Explanations marked AI-generated come from a model: review them before use."
        )
    return "\n".join(lines) + "\n"
